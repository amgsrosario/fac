-- Isolated foundation: no changes to existing documentary tables.
CREATE TABLE financial_operation (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id bigint NOT NULL REFERENCES empresa(id),
 cliente_id bigint NOT NULL REFERENCES cliente(id),
 moeda_id varchar(3) NOT NULL REFERENCES moeda(id),
 kind varchar(20) NOT NULL CHECK(kind IN ('CREATE','SETTLE','REVERSE')),
 request_key varchar(120) NOT NULL CHECK(length(trim(request_key))>0),
 request_payload text NOT NULL,
 actor varchar(100) NOT NULL CHECK(length(trim(actor))>0),
 reason varchar(500) NOT NULL,
 created_at timestamptz NOT NULL DEFAULT current_timestamp,
 created_tx bigint NOT NULL DEFAULT txid_current(),
 reverse_of bigint UNIQUE REFERENCES financial_operation(id),
 UNIQUE(empresa_id,request_key), UNIQUE(id,empresa_id,cliente_id,moeda_id),
 CHECK ((kind='REVERSE')=(reverse_of IS NOT NULL))
);
CREATE TABLE financial_position (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id bigint NOT NULL REFERENCES empresa(id),
 cliente_id bigint NOT NULL REFERENCES cliente(id),
 moeda_id varchar(3) NOT NULL REFERENCES moeda(id),
 nature varchar(10) NOT NULL CHECK(nature IN ('DEBT','CREDIT')),
 origin varchar(120) NOT NULL CHECK(length(trim(origin))>0),
 reference varchar(200),
 original numeric(19,2) NOT NULL CHECK(original>0),
 available numeric(19,2) NOT NULL CHECK(available>=0 AND available<=original),
 cancelled boolean NOT NULL DEFAULT false,
 creation_id bigint NOT NULL UNIQUE,
 created_at timestamptz NOT NULL DEFAULT current_timestamp,
 UNIQUE(empresa_id,origin), UNIQUE(id,empresa_id,cliente_id,moeda_id),
 FOREIGN KEY(creation_id,empresa_id,cliente_id,moeda_id) REFERENCES financial_operation(id,empresa_id,cliente_id,moeda_id),
 CHECK(NOT cancelled OR available=0)
);
CREATE TABLE financial_allocation (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 operation_id bigint NOT NULL,
 position_id bigint NOT NULL,
 empresa_id bigint NOT NULL, cliente_id bigint NOT NULL, moeda_id varchar(3) NOT NULL,
 amount numeric(19,2) NOT NULL CHECK(amount>0),
 effect varchar(10) NOT NULL CHECK(effect IN ('CONSUME','RESTORE','CANCEL')),
 reverse_of bigint UNIQUE REFERENCES financial_allocation(id),
 UNIQUE(operation_id,position_id),
 FOREIGN KEY(operation_id,empresa_id,cliente_id,moeda_id) REFERENCES financial_operation(id,empresa_id,cliente_id,moeda_id),
 FOREIGN KEY(position_id,empresa_id,cliente_id,moeda_id) REFERENCES financial_position(id,empresa_id,cliente_id,moeda_id),
 CHECK ((effect IN ('RESTORE','CANCEL'))=(reverse_of IS NOT NULL))
);
CREATE TABLE financial_component (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 operation_id bigint NOT NULL REFERENCES financial_operation(id),
 kind varchar(12) NOT NULL CHECK(kind IN ('CASH_IN','CASH_OUT','DISCOUNT')),
 amount numeric(19,2) NOT NULL CHECK(amount>0),
 reversed boolean NOT NULL DEFAULT false,
 reverse_of bigint UNIQUE REFERENCES financial_component(id),
 UNIQUE(operation_id,kind), CHECK(reversed=(reverse_of IS NOT NULL))
);
CREATE INDEX financial_allocation_position ON financial_allocation(position_id,operation_id);
CREATE FUNCTION financial_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Financial history is immutable'; END $$;
CREATE TRIGGER financial_operation_immutable BEFORE UPDATE OR DELETE ON financial_operation FOR EACH ROW EXECUTE FUNCTION financial_immutable();
CREATE TRIGGER financial_allocation_immutable BEFORE UPDATE OR DELETE ON financial_allocation FOR EACH ROW EXECUTE FUNCTION financial_immutable();
CREATE TRIGGER financial_component_immutable BEFORE UPDATE OR DELETE ON financial_component FOR EACH ROW EXECUTE FUNCTION financial_immutable();
CREATE FUNCTION financial_position_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Financial positions cannot be deleted'; END IF;
 IF (NEW.id,NEW.empresa_id,NEW.cliente_id,NEW.moeda_id,NEW.nature,NEW.origin,NEW.reference,NEW.original,NEW.creation_id,NEW.created_at)
 IS DISTINCT FROM (OLD.id,OLD.empresa_id,OLD.cliente_id,OLD.moeda_id,OLD.nature,OLD.origin,OLD.reference,OLD.original,OLD.creation_id,OLD.created_at)
 THEN RAISE EXCEPTION 'Financial position identity is immutable'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER financial_position_guard BEFORE UPDATE OR DELETE ON financial_position FOR EACH ROW EXECUTE FUNCTION financial_position_guard();
-- Deferred consistency protects projections and conservation at transaction commit.
CREATE FUNCTION financial_check_position() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE p financial_position; consumed numeric;
BEGIN
 IF TG_TABLE_NAME='financial_position' THEN SELECT * INTO p FROM financial_position WHERE id=NEW.id;
 ELSE SELECT * INTO p FROM financial_position WHERE id=NEW.position_id; END IF;
 SELECT coalesce(sum(CASE effect WHEN 'CONSUME' THEN amount WHEN 'RESTORE' THEN -amount ELSE 0 END),0)
 INTO consumed FROM financial_allocation WHERE position_id=p.id;
 IF p.cancelled IS DISTINCT FROM EXISTS(SELECT 1 FROM financial_operation WHERE reverse_of=p.creation_id) OR (NOT p.cancelled AND p.available<>p.original-consumed) OR (p.cancelled AND consumed<>0)
 THEN RAISE EXCEPTION 'Financial projection mismatch'; END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER financial_position_consistency AFTER INSERT OR UPDATE ON financial_position DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION financial_check_position();
CREATE CONSTRAINT TRIGGER financial_allocation_consistency AFTER INSERT ON financial_allocation DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION financial_check_position();
CREATE FUNCTION financial_check_operation() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE op financial_operation; original_op financial_operation; debt numeric; credit numeric; cash_in numeric; cash_out numeric; discount numeric;
BEGIN
 IF TG_TABLE_NAME='financial_operation' THEN op:=NEW;
 ELSE SELECT * INTO op FROM financial_operation WHERE id=NEW.operation_id; END IF;
 IF op.kind='SETTLE' THEN
 IF EXISTS(SELECT 1 FROM financial_allocation WHERE operation_id=op.id AND effect<>'CONSUME') OR EXISTS(SELECT 1 FROM financial_component WHERE operation_id=op.id AND reversed) THEN RAISE EXCEPTION 'Invalid settlement effects'; END IF;
 SELECT coalesce(sum(a.amount) FILTER (WHERE p.nature='DEBT'),0),coalesce(sum(a.amount) FILTER (WHERE p.nature='CREDIT'),0)
 INTO debt,credit FROM financial_allocation a JOIN financial_position p ON p.id=a.position_id WHERE a.operation_id=op.id;
 SELECT coalesce(sum(amount) FILTER (WHERE kind='CASH_IN'),0),coalesce(sum(amount) FILTER (WHERE kind='CASH_OUT'),0),coalesce(sum(amount) FILTER (WHERE kind='DISCOUNT'),0)
 INTO cash_in,cash_out,discount FROM financial_component WHERE operation_id=op.id;
 IF debt+cash_out<>credit+cash_in+discount OR discount>debt OR NOT EXISTS(SELECT 1 FROM financial_allocation WHERE operation_id=op.id)
 THEN RAISE EXCEPTION 'Unbalanced financial operation'; END IF;
 END IF;
 IF op.kind='CREATE' AND (NOT EXISTS(SELECT 1 FROM financial_position WHERE creation_id=op.id) OR EXISTS(SELECT 1 FROM financial_allocation WHERE operation_id=op.id) OR EXISTS(SELECT 1 FROM financial_component WHERE operation_id=op.id))
 THEN RAISE EXCEPTION 'Creation without position'; END IF;
 IF op.kind='REVERSE' THEN
 SELECT * INTO original_op FROM financial_operation WHERE id=op.reverse_of;
 IF original_op.kind='REVERSE' OR (op.empresa_id,op.cliente_id,op.moeda_id) IS DISTINCT FROM (original_op.empresa_id,original_op.cliente_id,original_op.moeda_id)
 THEN RAISE EXCEPTION 'Invalid reversal scope'; END IF;
 IF original_op.kind='CREATE' THEN
 IF NOT EXISTS(SELECT 1 FROM financial_position WHERE creation_id=original_op.id AND cancelled)
 OR EXISTS(SELECT 1 FROM financial_allocation WHERE operation_id=op.id)
 OR EXISTS(SELECT 1 FROM financial_component WHERE operation_id=op.id)
 THEN RAISE EXCEPTION 'Invalid creation reversal'; END IF;
 ELSE
 IF EXISTS(SELECT 1 FROM financial_allocation a WHERE a.operation_id=original_op.id AND NOT EXISTS(SELECT 1 FROM financial_allocation b WHERE b.operation_id=op.id AND b.reverse_of=a.id AND b.position_id=a.position_id AND b.amount=a.amount AND b.effect='RESTORE'))
 OR EXISTS(SELECT 1 FROM financial_allocation b WHERE b.operation_id=op.id AND NOT EXISTS(SELECT 1 FROM financial_allocation a WHERE a.id=b.reverse_of AND a.operation_id=original_op.id AND a.amount=b.amount AND a.position_id=b.position_id AND b.effect='RESTORE'))
 THEN RAISE EXCEPTION 'Invalid allocation reversal'; END IF;
 IF EXISTS(SELECT 1 FROM financial_component a WHERE a.operation_id=original_op.id AND NOT EXISTS(SELECT 1 FROM financial_component b WHERE b.operation_id=op.id AND b.reverse_of=a.id AND b.amount=a.amount AND b.reversed AND b.kind=CASE a.kind WHEN 'CASH_IN' THEN 'CASH_OUT' WHEN 'CASH_OUT' THEN 'CASH_IN' ELSE 'DISCOUNT' END))
 OR EXISTS(SELECT 1 FROM financial_component b WHERE b.operation_id=op.id AND NOT EXISTS(SELECT 1 FROM financial_component a WHERE a.id=b.reverse_of AND a.operation_id=original_op.id AND a.amount=b.amount AND b.reversed AND b.kind=CASE a.kind WHEN 'CASH_IN' THEN 'CASH_OUT' WHEN 'CASH_OUT' THEN 'CASH_IN' ELSE 'DISCOUNT' END))
 THEN RAISE EXCEPTION 'Invalid monetary reversal'; END IF;
 END IF;
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER financial_operation_consistency AFTER INSERT ON financial_operation DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION financial_check_operation();

CREATE CONSTRAINT TRIGGER financial_allocation_operation_consistency AFTER INSERT ON financial_allocation DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION financial_check_operation();
CREATE CONSTRAINT TRIGGER financial_component_operation_consistency AFTER INSERT ON financial_component DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION financial_check_operation();
CREATE FUNCTION financial_append_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM financial_operation WHERE id=NEW.operation_id AND created_tx=txid_current())
 THEN RAISE EXCEPTION 'Cannot append to a consolidated financial operation'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER financial_allocation_append BEFORE INSERT ON financial_allocation FOR EACH ROW EXECUTE FUNCTION financial_append_guard();
CREATE TRIGGER financial_component_append BEFORE INSERT ON financial_component FOR EACH ROW EXECUTE FUNCTION financial_append_guard();
